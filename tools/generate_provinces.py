"""Generate platform catalogues from shared/regions/provinces.json."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
ROWS = json.loads((ROOT / 'shared/regions/provinces.json').read_text(encoding='utf-8'))
def write(name, value):
    path = ROOT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding='utf-8')
def quoted(value):
    return json.dumps(value, ensure_ascii=False)
write('frontend/src/common/region/ProvinceCatalog.js', '''// Generated by tools/generate_provinces.py. Edit the shared catalogue.
export const ProvinceCatalog = Object.freeze(''' + json.dumps(ROWS, ensure_ascii=False, indent=2) + '''.map(row => Object.freeze({ ...row, aliases: Object.freeze(row.aliases) })))
export function provinceCode(value) {
  const text = typeof value === 'string' ? value.trim() : ''
  const row = ProvinceCatalog.find(p => p.code === text.toUpperCase() || p.name === text ||
    p.aliases.some(a => a.toLowerCase() === text.toLowerCase()) || (/^\\d{6}$/.test(text) && text.startsWith(p.prefix)))
  return row?.code || ''
}
export function provinceName(value) {
  return ProvinceCatalog.find(p => p.code === provinceCode(value))?.name || (value?.trim() ? '未识别地区' : '地区未填写')
}
export function requireProvinceCode(value) {
  const code = provinceCode(value)
  if (!code) throw new Error('请选择有效的省级地区')
  return code
}
''')
